    private void btnNuevaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnNuevaActionPerformed
        if (controlador.hayPartidaEnCurso()) {
            int respuesta = JOptionPane.showConfirmDialog(this,
                    "Hay una simulación en curso. Si empezás una nueva se pierde.\n¿Querés continuar?",
                    "Nueva simulación", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);
            if (respuesta != JOptionPane.YES_OPTION) {
                return;
            }
        }
        controlador.nuevaSimulacion();
    }//GEN-LAST:event_btnNuevaActionPerformed

    // ---- lo que el controlador le pide a la vista ----
    public void mostrarContadores(int turno, int turnosTotales, String clima, int plantas,
            int conejos, int lobos) {
        lblTurno.setText("Turno: " + turno + " / " + turnosTotales);
        lblClima.setText("Clima: " + clima);
        lblPlantas.setText("Plantas: " + plantas);
        lblConejos.setText("Conejos: " + conejos);
        lblLobos.setText("Lobos: " + lobos);
    }

    // reemplaza todas las filas de la tabla por las que manda el controlador
    public void mostrarEntidades(Object[][] filas) {
        DefaultTableModel tabla = (DefaultTableModel) tblEntidades.getModel();
        tabla.setRowCount(0);
        for (Object[] fila : filas) {
            tabla.addRow(fila);
        }
    }

    public void mostrarEventos(int turno, List<String> eventos) {
        lblTituloEventos.setText("Eventos del turno " + turno);
        if (eventos.isEmpty()) {
            if (turno == 0) {
                lstEventos.setListData(new String[]{"Todavía no se jugó ningún turno."});
            } else {
                lstEventos.setListData(new String[]{"Sin eventos en este turno."});
            }
        } else {
            lstEventos.setListData(eventos.toArray(new String[0]));
        }
    }

    // habilita o deshabilita los controles de intervención y explica el motivo
    public void actualizarIntervencion(boolean disponible, String estado, int lobosDisponibles) {
        lblEstadoIntervencion.setText(estado);
        cmbClimaIntervencion.setEnabled(disponible);
        btnCambiarClima.setEnabled(disponible);
        cmbTipoEntidad.setEnabled(disponible);
        txtEnergia.setEnabled(disponible);
        btnAgregarEntidad.setEnabled(disponible);
        lblLobosRestantes.setText("Lobos que se pueden agregar: " + lobosDisponibles);
    }

    public void habilitarAvance(boolean habilitado) {
        btnAvanzar.setEnabled(habilitado);
    }

    public void habilitarVerReporte(boolean habilitado) {
        btnVerReporte.setEnabled(habilitado);
    }

    public void mostrarMensaje(String mensaje) {
        lblMensaje.setText(mensaje);
    }

    // estado vacío: no hay simulación en curso
    public void mostrarSinSimulacion() {
        lblTurno.setText("Turno: -");
        lblClima.setText("Clima: -");
        lblPlantas.setText("Plantas: -");
        lblConejos.setText("Conejos: -");
        lblLobos.setText("Lobos: -");
        mostrarEntidades(new Object[0][0]);
        lblTituloEventos.setText("Eventos del turno");
        lstEventos.setListData(new String[]{"No hay una simulación en curso."});
        actualizarIntervencion(false, "No hay una simulación en curso: no se puede intervenir.", 0);
        lblLobosRestantes.setText("Lobos que se pueden agregar: -");
        btnAvanzar.setEnabled(false);
        btnVerReporte.setEnabled(false);
        lblMensaje.setText("No hay una simulación en curso. Configurá una desde la pantalla \"Configuración\".");
    }

