    private void btnIniciarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIniciarActionPerformed
        if (controlador.hayPartidaEnCurso()) {
            int respuesta = JOptionPane.showConfirmDialog(this,
                    "Hay una simulación en curso. Si empezás una nueva se pierde.\n¿Querés continuar?",
                    "Nueva simulación", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);
            if (respuesta != JOptionPane.YES_OPTION) {
                return;
            }
        }
        controlador.configurarSimulacion(txtPlantas.getText(), txtConejos.getText(),
                txtLobos.getText(), (String) cmbClima.getSelectedItem(), txtTurnos.getText());
    }//GEN-LAST:event_btnIniciarActionPerformed

