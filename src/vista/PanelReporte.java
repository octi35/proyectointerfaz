    public void mostrarTexto(String causaFin, String texto) {
        lblCausaFin.setText("Causa de fin: " + causaFin);
        txtReporte.setText(texto);
        txtReporte.setCaretPosition(0);
    }

    // estado vacío: todavía no terminó ninguna simulación
    public void mostrarVacio() {
        lblCausaFin.setText("Causa de fin: -");
        txtReporte.setText("Todavía no hay reporte.\n\n"
                + "El reporte final se genera cuando termina la simulación:\n"
                + "se completan los turnos o colapsa el ecosistema.");
        txtReporte.setCaretPosition(0);
    }

